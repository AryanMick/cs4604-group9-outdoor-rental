-- CS4604 Group 9 | Outdoor Equipment Rental Management System
-- PostgreSQL 15+. Run once in an empty database; no existing schema is dropped.
BEGIN;
CREATE SCHEMA rental;
SET search_path TO rental, public;

CREATE TABLE business (
    business_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name VARCHAR(120) NOT NULL CHECK (btrim(business_name) <> ''),
    address VARCHAR(255) NOT NULL CHECK (btrim(address) <> '')
);

CREATE TABLE rental_equipment (
    equipment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_type VARCHAR(60) NOT NULL CHECK (btrim(equipment_type) <> ''),
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('AVAILABLE', 'MAINTENANCE', 'RETIRED')),
    business_id INTEGER NOT NULL REFERENCES business(business_id)
);

CREATE TABLE customer (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL CHECK (btrim(first_name) <> ''),
    last_name VARCHAR(80) NOT NULL CHECK (btrim(last_name) <> ''),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (btrim(email) <> '')
);

CREATE TABLE reservation (
    reservation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id INTEGER NOT NULL REFERENCES rental_equipment(equipment_id),
    customer_id INTEGER NOT NULL REFERENCES customer(customer_id),
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('RESERVED', 'CHECKED_OUT', 'RETURNED', 'CANCELLED')),
    checkout_date DATE NOT NULL,
    due_date DATE NOT NULL,
    CONSTRAINT reservation_date_order CHECK (due_date > checkout_date)
);

CREATE TABLE payment (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id INTEGER NOT NULL UNIQUE REFERENCES reservation(reservation_id),
    amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    payment_date DATE NOT NULL
);

CREATE TABLE manager (
    manager_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL CHECK (btrim(first_name) <> ''),
    last_name VARCHAR(80) NOT NULL CHECK (btrim(last_name) <> ''),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (btrim(email) <> ''),
    business_id INTEGER NOT NULL REFERENCES business(business_id)
);

CREATE TABLE employee (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL CHECK (btrim(first_name) <> ''),
    last_name VARCHAR(80) NOT NULL CHECK (btrim(last_name) <> ''),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (btrim(email) <> ''),
    manager_id INTEGER NOT NULL REFERENCES manager(manager_id)
);

CREATE TABLE admin (
    admin_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL CHECK (btrim(first_name) <> ''),
    last_name VARCHAR(80) NOT NULL CHECK (btrim(last_name) <> '')
);

-- Access grants concern an employee under that employee's assigned manager.
-- Derive the manager through employee.manager_id; do not repeat it here.
CREATE TABLE defines_access (
    admin_id INTEGER NOT NULL REFERENCES admin(admin_id),
    employee_id INTEGER NOT NULL REFERENCES employee(employee_id),
    PRIMARY KEY (admin_id, employee_id)
);

CREATE TABLE admin_privileges (
    admin_id INTEGER NOT NULL REFERENCES admin(admin_id),
    privilege VARCHAR(60) NOT NULL CHECK (btrim(privilege) <> ''),
    PRIMARY KEY (admin_id, privilege)
);

CREATE INDEX equipment_business_idx ON rental_equipment(business_id);
CREATE INDEX reservation_equipment_idx ON reservation(equipment_id);
CREATE INDEX reservation_customer_idx ON reservation(customer_id);
CREATE INDEX manager_business_idx ON manager(business_id);
CREATE INDEX employee_manager_idx ON employee(manager_id);
CREATE INDEX access_employee_idx ON defines_access(employee_id);

-- Views display derived information without duplicating it in base tables.
CREATE VIEW reservation_details AS
SELECT r.reservation_id, c.first_name || ' ' || c.last_name AS customer,
       e.equipment_id, e.equipment_type, b.business_name,
       r.status, r.checkout_date, r.due_date, p.amount AS payment_amount
FROM reservation r
JOIN customer c ON c.customer_id = r.customer_id
JOIN rental_equipment e ON e.equipment_id = r.equipment_id
JOIN business b ON b.business_id = e.business_id
LEFT JOIN payment p ON p.reservation_id = r.reservation_id;

CREATE VIEW employee_details AS
SELECT e.employee_id, e.first_name, e.last_name, e.email,
       m.manager_id, m.first_name || ' ' || m.last_name AS manager,
       b.business_id, b.business_name
FROM employee e
JOIN manager m ON m.manager_id = e.manager_id
JOIN business b ON b.business_id = m.business_id;

COMMIT;
